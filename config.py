def get_rank(troops: int) -> str:
    """Р—РІР°РЅРёРµ РїРѕ РІРѕР№СЃРєР°Рј (Р°РІС‚РѕРјР°С‚РёС‡РµСЃРєРѕРµ, РґРѕ Р»СЋР±РѕРіРѕ СѓСЂРѕРІРЅСЏ)."""
    rank = RANKS[0][0]
    for rank_name, required in RANKS:
        if troops >= required:
            rank = rank_name

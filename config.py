def get_next_rank(troops: int) -> tuple:
    for rank_name, required in RANKS:
        if troops < required:
            return rank_name, required
    return RANKS[-1][0], RANKS[-1][1]


def get_rank_index(troops: int) -> int:
    for i, (rank_name, required) in enumerate(RANKS):
        if troops < required:
            return max(0, i - 1)
    return len(RANKS) - 1



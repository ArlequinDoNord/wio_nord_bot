"""Формирования ВВС Нордхайма.

Источник истины — таблица `wings` (БД). Здесь живёт только кэш меток:
WINGS (полные: «🐺 1 АК «Небесные Волки»») и WINGS_SHORT (короткие:
«🐺 1 АК») — плюс функции-читатели.

Метка всегда «число + две заглавные буквы» (например «1 АК», «5 ИШ»):
номер и аббревиатура хранятся отдельными полями, чтобы legacy-крылья
(ключи '1'..'4') и новые формирования (ключ 'N АБ') собирались одинаково.

set_wings() пересобирает кэш из строк БД; вызывается при старте и после
каждого изменения (добавление/переименование/удаление) в штабе.
"""

# Ключ → полная метка формирования (для профиля, штаба, мастеров админки).
# Модуль стартует с legacy-крыльями — до первой загрузки из БД.
WINGS = {
    "1": "🐺 1 АК «Небесные Волки»",
    "2": "🦉 2 АК «Полярные Совы»",
    "3": "🌑 3 АК «Тени Нордхама»",
    "4": "❄️ 4 СО «Polaris» (спец отряд)",
}

# Короткие метки (для кнопок штаба)
WINGS_SHORT = {
    "1": "🐺 1 АК",
    "2": "🦉 2 АК",
    "3": "🌑 3 АК",
    "4": "❄️ 4 СО",
}


def set_wings(rows) -> None:
    """Пересобрать кэш меток из строк таблицы wings (упорядочено по sort_order).

    rows — айос.ходить rows с полями: key, num, abbr, callsign, emoji.
    """
    global WINGS, WINGS_SHORT
    WINGS = {}
    WINGS_SHORT = {}
    for r in rows:
        key = r['key']
        short = f"{r['emoji'] or ''} {r['num']} {r['abbr']}".strip()
        WINGS_SHORT[key] = short
        full = f"{short} «{r['callsign']}»" if r.get('callsign') else short
        low = (r.get('name') or "").lower()
        if low == "спец отряд":
            full += f" ({low})"
        WINGS[key] = full


def wing_label(key) -> str:
    """Человекочитаемая метка формирования по ключу; None/неизвестный ключ → пустая строка."""
    if not key:
        return ""
    return WINGS.get(str(key), "") or ""


def all_wings() -> dict:
    """Все метки формирований (ключ → полная метка) из актуального кэша.

    Отдельная функция, а не импорт WINGS: set_wings() пересобирает словарь,
    поэтому импортированная копия устаревает после переименования в штабе.
    """
    return dict(WINGS)


def all_wings_short() -> dict:
    """Все короткие метки (ключ → «🐺 1 АК») из актуального кэша."""
    return dict(WINGS_SHORT)


def wing_short(key) -> str:
    """Короткая метка формирования («🐺 1 АК»); неизвестный ключ → пустая строка."""
    if not key:
        return ""
    return WINGS_SHORT.get(str(key), "") or ""


def wing_display(key) -> str:
    """Метка формирования или «— не назначено», если пилот без формирования."""
    label = wing_label(key)
    return label if label else "— не назначено"
"""Авиакрылья ВВС Нордхайма.

Хранимое значение у пилота — строковый ключ ('1'/'2'/'3') или NULL (нет крыла).
Отображение (метки) собрано в одном месте, чтобы профиль, штаб и админка
использовали одинаковые названия.
"""

# Ключ → полная метка авиакрыла (для профиля, штаба, мастеров админки)
WINGS = {
    "1": "🦅 1 АК «Небесные Волки»",
    "2": "🦉 2 АК «Полярные Совы»",
    "3": "🌑 3 АК «Тени Нордхама»",
}


def wing_label(key) -> str:
    """Человекочитаемая метка крыла по ключу; None/неизвестный ключ → пустая строка."""
    if not key:
        return ""
    return WINGS.get(str(key), "") or ""


def wing_display(key) -> str:
    """Метка крыла или «— не назначено», если пилот без крыла."""
    label = wing_label(key)
    return label if label else "— не назначено"
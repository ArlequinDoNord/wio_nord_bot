# Версия сборки. Отдельный файл, а не config.py: при бампе меняется только он,
# и tools/run_smokes.py --related не тянет весь набор смоуков (config.py импортируют
# почти все смоуки). config.py реэкспортирует эти константы, поэтому
# `from config import VERSION` работает как раньше.
#
# Семантическое версионирование (SemVer): MAJOR.MINOR.PATCH
# - PATCH (x.x.1): исправление ошибок / мелкие правки
# - MINOR (x.1.x): новая функциональность (обратно совместимая)
# - MAJOR (1.x.0): крупные ломающие изменения (до 1.0 — на усмотрение)
# Стартуем с 0.1.0 (нестабильная фаза).

